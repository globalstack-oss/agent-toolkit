// Bundles each script into one dependency-free file next to the skill that uses it, and writes the Cursor
// manifests from the Claude ones, so each manifest has one source.
import { copyFileSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { build } from 'esbuild';

const json = (path) => JSON.parse(readFileSync(path, 'utf8'));
const write = (path, value) => writeFileSync(path, `${JSON.stringify(value, null, 2)}\n`);
const plugin = json('plugin/.claude-plugin/plugin.json');

// gs.mjs compares its version with the plugin.json on the public repository's main branch, which is what an update
// installs.
const { repository, latest } = json('package.json').config;
const release = { version: plugin.version, repository, latest };

const common = { bundle: true, platform: 'node', target: 'node20', format: 'esm', legalComments: 'none', banner: { js: '#!/usr/bin/env node\n// Generated by build.mjs from src/. Do not edit.' } };
await build({ ...common, entryPoints: ['src/cli/gs.ts'], outfile: 'plugin/skills/globalstack-integration/scripts/gs.mjs', define: { __PLUGIN__: JSON.stringify(release) } });
await build({ ...common, entryPoints: ['src/cli/sandbox.ts'], outfile: 'plugin/skills/globalstack-testing/scripts/sandbox.mjs' });

write('plugin/.cursor-plugin/plugin.json', plugin);
// The license goes with each way the plugin installs: the whole plugin, and each skill folder copied on its own.
for (const dir of ['plugin', ...readdirSync('plugin/skills').map((name) => `plugin/skills/${name}`)]) copyFileSync('LICENSE', `${dir}/LICENSE`);
// Cursor wants the plugin folder without the leading "./".
const marketplace = json('.claude-plugin/marketplace.json');
write('.cursor-plugin/marketplace.json', { ...marketplace, plugins: marketplace.plugins.map((p) => ({ ...p, source: p.source.replace(/^\.\//, '') })) });
